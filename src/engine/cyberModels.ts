/** Attack categories detected by the risk engine */
export type AttackCategory =
  | 'ransomware'
  | 'dos_attack'
  | 'unauthorized_insider'
  | 'credential_stuffing'
  | 'unauthorized_scada_access'
  | 'suspicious_remote_login'
  | 'unauthorized_control_command'
  | 'repeated_auth_failure'
  | 'abnormal_generator_shutdown'
  | 'suspicious_substation_switching'
  | 'transmission_line_trip'
  | 'unauthorized_agc_modification'
  | 'abnormal_grid_telemetry'
  | 'malware_detected'
  | 'data_exfiltration'
  | 'unknown';

export type AttackStatus = 'detected' | 'investigating' | 'confirmed' | 'mitigated' | 'false_positive';

export type RiskCategory = 'low' | 'medium' | 'high' | 'critical';

export type EventOrigin = 'simulated_attack' | 'siem_alert' | 'ids_alert' | 'manual_report' | 'grid_telemetry' | 'scada_monitor';

export type AlertSeverity = 'info' | 'warning' | 'critical' | 'emergency';

/** Inbound security event from an attacker machine / SIEM */
export interface CyberEvent {
  eventId: string;
  timestamp: string;            // ISO 8601
  sourceIP: string;
  destIP: string;
  attackCategory: AttackCategory;
  targetAssetId: string;        // Maps to GridAtlas asset ID
  description: string;
  detectionSource: EventOrigin;
  attackStatus: AttackStatus;
  confidenceLevel: number;      // 0.0 – 1.0
  rawPayload?: string;          // Optional evidence / packet summary
}

/** Risk alert generated by the risk engine */
export interface RiskAlert {
  alertId: string;
  eventId: string;              // Links back to source event
  timestamp: string;
  attackType: AttackCategory;
  sourceIP: string;
  targetAssetId: string;
  targetAssetName: string;
  riskScore: number;            // 0–100
  riskCategory: RiskCategory;
  affectedGenerationMW: number;
  currentGridImpact: string;
  recommendedAction: string;
  explanation: string;          // Why this risk score
  severity: AlertSeverity;
  isRead: boolean;
  isAcknowledged: boolean;
  acknowledgedBy?: string;
  acknowledgedAt?: string;
}

/** Financial incident analysis linked to a risk alert */
export interface FinancialIncident {
  incidentId: string;
  alertId: string;
  eventId: string;
  timestamp: string;
  targetAssetId: string;
  targetAssetName: string;
  attackCategory: AttackCategory;

  // ---- Outage Parameters ----
  affectedGenerationMW: number;
  assumedOutageDurationHrs: number;
  ratedCapacityMW: number;

  // ---- Cost Breakdown ----
  replacementElectricityCost: number;   // ₹ or $
  normalGenerationCost: number;
  unservedElectricityImpact: number;
  recoveryExpenses: number;
  operationalExpenses: number;
  totalEstimatedLoss: number;

  // ---- Ranges ----
  minExpectedLoss: number;
  maxExpectedLoss: number;

  // ---- Annualized ----
  annualLossEventFrequency: number;
  averageLossMagnitude: number;
  annualizedExpectedLoss: number;

  // ---- Assumptions ----
  replacementCostPerKWh: number;
  normalCostPerKWh: number;
  economicImpactPerMWh: number;
  calculationExplanation: string;

  // ---- Label ----
  isEstimate: true;              // Always true — these are projections
}

/** Per-asset risk status for 3D/Map overlay */
export interface AssetRiskStatus {
  assetId: string;
  status: 'normal' | 'suspicious' | 'compromised';
  riskScore: number;
  activeAlertCount: number;
  latestAlertId?: string;
}

/** Notification for the in-app bell system */
export interface CyberNotification {
  id: string;
  timestamp: string;
  severity: AlertSeverity;
  title: string;
  message: string;
  assetId?: string;
  alertId?: string;
  isRead: boolean;
}

/** Financial summary for the dashboard */
export interface FinancialSummary {
  totalFinancialExposure: number;
  currentIncidentLoss: number;
  totalReplacementCost: number;
  totalRecoveryCost: number;
  totalOperationalCost: number;
  totalUnservedImpact: number;
  incidentCount: number;
  assetExposure: { assetId: string; assetName: string; exposure: number }[];
  incidentExposure: { incidentId: string; loss: number; attackType: AttackCategory }[];
}

/** WebSocket message types sent from server → client */
export type WSMessage =
  | { type: 'new_event'; payload: CyberEvent }
  | { type: 'new_alert'; payload: RiskAlert }
  | { type: 'new_incident'; payload: FinancialIncident }
  | { type: 'alert_acknowledged'; payload: { alertId: string } }
  | { type: 'asset_risk_update'; payload: AssetRiskStatus[] }
  | { type: 'financial_summary'; payload: FinancialSummary }
  | { type: 'reset_telemetry'; payload: any }
  | { type: 'connection_established'; payload: { serverTime: string } };
